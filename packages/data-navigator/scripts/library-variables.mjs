// Writes static snapshots of the CSS variables of Mantine and Ant Design that our theme files read, light and dark, to
// `demo/variables/`. The demo runs no library code: these files stand in for what the libraries set at runtime in a
// real app. Run it with `npm run library-variables` after a library update.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);

// The library variables a theme file reads.
function neededBy(themeFile, prefix) {
  const css = readFileSync(themeFile, 'utf8');

  return [...new Set([...css.matchAll(new RegExp(`var\\((--${prefix}-[a-z0-9-]+)\\)`, 'g'))].map((match) => match[1]))]
    .sort();
}

// The declarations of the first rule whose selector starts with `selector`.
function declarations(css, selector) {
  const start = css.indexOf(selector);
  const body = css.slice(css.indexOf('{', start) + 1, css.indexOf('}', start));
  const result = new Map();

  for (const match of body.matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/g)) {
    result.set(match[1], match[2].replace(/\s+/g, ' ').trim());
  }

  return result;
}

// The variables and every variable their values refer to, looked up in the given maps (the first one that has it).
function closure(names, maps) {
  const result = new Map();
  const todo = [...names];

  while (todo.length > 0) {
    const name = todo.pop();

    if (result.has(name)) {
      continue;
    }

    const value = maps.map((map) => map.get(name)).find((found) => found !== undefined);

    if (value === undefined) {
      throw new Error(`no value for ${name}`);
    }

    result.set(name, value);
    todo.push(...[...value.matchAll(/var\((--[a-z0-9-]+)/g)].map((match) => match[1]));
  }

  return new Map([...result].sort(([a], [b]) => a.localeCompare(b)));
}

function block(selector, variables, indent = '') {
  const lines = [...variables].map(([name, value]) => `${indent}  ${name}: ${value};`);

  return `${indent}${selector} {\n${lines.join('\n')}\n${indent}}`;
}

function write(file, library, light, dark) {
  const css =
    `/* Generated by scripts/library-variables.mjs: the ${library} variables the ${library} theme reads, with the default
   values of ${library}, light and dark. Do not edit. */
${block(':root', light)}

/* Dark: with the system's dark scheme (unless the page chose light with \`data-scheme\`), or when the page chose dark. */
@media (prefers-color-scheme: dark) {
${block(':root:not([data-scheme=\'light\'])', dark, '  ')}
}

${block(':root[data-scheme=\'dark\']', dark)}
`;

  writeFileSync(file, css);
  console.log(`${file}: ${light.size} variables, ${dark.size} of them dark`);
}

// Mantine: its default variables are a static file. The base block has what does not depend on the color scheme, the
// scheme blocks the rest (Mantine picks one with the data-mantine-color-scheme attribute, set by its provider).
{
  const css = readFileSync(require.resolve('@mantine/core/styles/default-css-variables.css'), 'utf8');
  const base = declarations(css, ':root,');
  const light = declarations(css, ':root[data-mantine-color-scheme=\'light\']');
  const dark = declarations(css, ':root[data-mantine-color-scheme=\'dark\']');
  const needed = neededBy('src/themes/mantine.ts', 'mantine');
  const lightVariables = closure(needed, [light, base]);
  const darkVariables = new Map(
    [...closure(needed, [dark, base])].filter(([name, value]) => lightVariables.get(name) !== value),
  );

  write('demo/variables/mantine.css', 'Mantine', lightVariables, darkVariables);
}

// Ant Design: its variables come from its design tokens, computed at runtime. The same tokens, in the same form as
// antd's own CSS variables (`--ant-` and the name in kebab case, numbers in px except the unitless ones).
{
  const { theme } = require('antd');
  const unitless = new Set(['fontWeightStrong', 'lineHeight', 'opacityLoading', 'zIndexBase', 'zIndexPopupBase']);
  const cssName = (token) =>
    `--ant-${
      token.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([A-Z]+)([A-Z][a-z0-9]+)/g, '$1-$2').replace(
        /([a-z])([A-Z0-9])/g,
        '$1-$2',
      ).toLowerCase()
    }`;
  const variables = (tokens) =>
    new Map(
      Object.entries(tokens)
        .filter(([, value]) => typeof value === 'string' || typeof value === 'number')
        .map(([token, value]) => [
          cssName(token),
          typeof value === 'number' && !unitless.has(token) ? `${value}px` : String(value).replace(/\s+/g, ' ').trim(),
        ]),
    );
  const needed = neededBy('src/themes/antd.ts', 'ant');
  const light = closure(needed, [variables(theme.getDesignToken())]);
  const darkAll = closure(needed, [variables(theme.getDesignToken({ algorithm: theme.darkAlgorithm }))]);
  const dark = new Map([...darkAll].filter(([name, value]) => light.get(name) !== value));

  write('demo/variables/antd.css', 'Ant Design', light, dark);
}
