// After the Vite build: writes the page AttachmentManager.Code into the XAR's content (target/classes), with the built
// module as its attachment (base64, as XWiki's XAR format wants it). Maven packages target/classes into the XAR.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const FILE = 'xwiki-attachment-manager.js';
const module = readFileSync(`target/js/${FILE}`);
const xml = `<?xml version="1.1" encoding="UTF-8"?>

<xwikidoc version="1.5" reference="AttachmentManager.Code" locale="">
  <web>AttachmentManager</web>
  <name>Code</name>
  <language/>
  <defaultLanguage/>
  <translation>0</translation>
  <creator>xwiki:XWiki.Admin</creator>
  <parent>AttachmentManager.WebHome</parent>
  <author>xwiki:XWiki.Admin</author>
  <contentAuthor>xwiki:XWiki.Admin</contentAuthor>
  <version>1.1</version>
  <title>Attachment Manager Code</title>
  <comment/>
  <minorEdit>false</minorEdit>
  <syntaxId>xwiki/2.1</syntaxId>
  <hidden>true</hidden>
  <content>The code of the attachment manager: the ES module, attached to this page (generated by the build).</content>
  <attachment>
    <filename>${FILE}</filename>
    <mimetype>text/javascript</mimetype>
    <filesize>${module.length}</filesize>
    <author>xwiki:XWiki.Admin</author>
    <version>1.1</version>
    <comment/>
    <content>${module.toString('base64')}</content>
  </attachment>
</xwikidoc>
`;

mkdirSync('target/classes/AttachmentManager', { recursive: true });
writeFileSync('target/classes/AttachmentManager/Code.xml', xml);
console.log(`target/classes/AttachmentManager/Code.xml: ${FILE}, ${module.length} bytes`);
